    assert.equal(await frame.locator('#paper').getAttribute('data-asset'),'image');
    assert(await frame.locator('#editButton').isDisabled());
    pass('图片预览与编辑禁用');
    await scene('视频成果');
    assert.equal(await frame.locator('#paper').getAttribute('data-asset'),'video');
    pass('视频首帧预览');
    await scene('选择参考资料');
    assert(await frame.locator('#referenceSearch').isVisible());
    await frame.locator('[data-reference-id]').first().click();
    assert(await frame.locator('#referenceSelected .bui-reference-chip').isVisible());
    pass('资料选择与引用标签');
    await scene('选择协作技能');
    assert(await frame.locator('.bui-skill-choice').count()>0);
    pass('技能选择');
    await scene('确认项目技能');
